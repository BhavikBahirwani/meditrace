package com.meditrace.dao;

import com.meditrace.exception.DataAccessException;
import com.meditrace.util.DBConnection;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Shared JDBC plumbing for every DAO (Template Method idea: the boring open / bind /
 * execute / map / close steps are written once here; each DAO only supplies SQL and a
 * {@link RowMapper}).
 * <p>
 * Rules followed everywhere:
 * <ul>
 *   <li><b>Only {@link PreparedStatement}</b> with {@code ?} placeholders - user input is
 *       never concatenated into SQL, which prevents SQL injection;</li>
 *   <li><b>try-with-resources</b> closes ResultSet, Statement and Connection automatically,
 *       even when an exception is thrown;</li>
 *   <li>{@link SQLException} is translated into {@link DataAccessException}.</li>
 * </ul>
 * Overloads that accept a {@link Connection} let a service run several DAO calls inside
 * one JDBC transaction (see {@code BatchService.registerBatch}).
 */
public abstract class AbstractDAO {

    /** Opens a connection from the singleton. */
    protected Connection open() throws DataAccessException {
        return DBConnection.getInstance().getConnection();
    }

    // ---------------------------------------------------------------- queries

    protected <R> List<R> queryList(String sql, RowMapper<R> mapper, Object... params) throws DataAccessException {
        try (Connection con = open()) {
            return queryList(con, sql, mapper, params);
        } catch (SQLException e) {
            throw new DataAccessException("Query failed: " + e.getMessage(), e);
        }
    }

    protected <R> List<R> queryList(Connection con, String sql, RowMapper<R> mapper, Object... params)
            throws DataAccessException {
        try (PreparedStatement ps = con.prepareStatement(sql)) {
            bind(ps, params);
            try (ResultSet rs = ps.executeQuery()) {
                List<R> results = new ArrayList<>();
                while (rs.next()) {
                    results.add(mapper.map(rs));
                }
                return results;
            }
        } catch (SQLException e) {
            throw new DataAccessException("Query failed: " + e.getMessage(), e);
        }
    }

    protected <R> Optional<R> queryOne(String sql, RowMapper<R> mapper, Object... params) throws DataAccessException {
        List<R> rows = queryList(sql, mapper, params);
        return rows.isEmpty() ? Optional.empty() : Optional.of(rows.get(0));
    }

    /** Runs a {@code SELECT COUNT(*) ...} style query and returns the first column. */
    protected long queryLong(String sql, Object... params) throws DataAccessException {
        return queryOne(sql, rs -> rs.getLong(1), params).orElse(0L);
    }

    // ---------------------------------------------------------------- updates

    protected int executeUpdate(String sql, Object... params) throws DataAccessException {
        try (Connection con = open()) {
            return executeUpdate(con, sql, params);
        } catch (SQLException e) {
            throw new DataAccessException("Update failed: " + e.getMessage(), e);
        }
    }

    protected int executeUpdate(Connection con, String sql, Object... params) throws DataAccessException {
        try (PreparedStatement ps = con.prepareStatement(sql)) {
            bind(ps, params);
            return ps.executeUpdate();
        } catch (SQLException e) {
            throw new DataAccessException("Update failed: " + e.getMessage(), e);
        }
    }

    /** INSERT that returns the AUTO_INCREMENT key generated by MySQL. */
    protected long insertAndGetKey(String sql, Object... params) throws DataAccessException {
        try (Connection con = open()) {
            return insertAndGetKey(con, sql, params);
        } catch (SQLException e) {
            throw new DataAccessException("Insert failed: " + e.getMessage(), e);
        }
    }

    protected long insertAndGetKey(Connection con, String sql, Object... params) throws DataAccessException {
        try (PreparedStatement ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            bind(ps, params);
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getLong(1);
                }
                throw new DataAccessException("Insert did not return a generated key");
            }
        } catch (SQLException e) {
            throw new DataAccessException("Insert failed: " + e.getMessage(), e);
        }
    }

    // ---------------------------------------------------------------- helpers

    /**
     * Binds parameters by position. Enums are stored by name (matching the MySQL ENUM
     * columns); {@code java.time} types are supported natively by Connector/J 8.
     */
    protected static void bind(PreparedStatement ps, Object... params) throws SQLException {
        for (int i = 0; i < params.length; i++) {
            Object p = params[i];
            if (p == null) {
                ps.setNull(i + 1, Types.NULL);
            } else if (p instanceof Enum<?> e) {          // pattern matching for instanceof (Java 16+)
                ps.setString(i + 1, e.name());
            } else {
                ps.setObject(i + 1, p);
            }
        }
    }

    /** Reads a nullable BIGINT column as {@code Long} (null stays null, unlike getLong). */
    protected static Long getNullableLong(ResultSet rs, String column) throws SQLException {
        long v = rs.getLong(column);
        return rs.wasNull() ? null : v;
    }

    /** Reads a nullable INT column as {@code Integer}. */
    protected static Integer getNullableInt(ResultSet rs, String column) throws SQLException {
        int v = rs.getInt(column);
        return rs.wasNull() ? null : v;
    }
}
